import { act, fireEvent, screen, waitFor, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { describe, expect, it, vi } from 'vitest'
import axe from 'axe-core'
import { deferred, failure, json, otherPollId, pollId } from '../../test/network'
import { creatorCommands } from './api'
import { authenticatedApp, draftPoll, fixture, writes } from './test-fixture'

const manage = '/polls/' + pollId + '/manage'
const detail = '/api/v2/polls/' + pollId + '/'
const route = () => screen.getByLabelText('Current route').textContent || ''
async function fillQuestion() {
  fireEvent.change(screen.getByLabelText('Question'), { target: { value: 'Which day works?' } })
  fireEvent.change(screen.getByLabelText('Option 1'), { target: { value: 'Monday' } })
  fireEvent.change(screen.getByLabelText('Option 2'), { target: { value: 'Tuesday' } })
}
describe('draft creation and publication', () => {
  it('saves an incomplete draft with one atomic creation request and no protected fields', async () => {
    const { fetcher, state } = fixture()
    await authenticatedApp('/polls/new')
    await userEvent.click(screen.getByRole('button', { name: 'Save draft' }))
    await screen.findByRole('heading', { level: 1, name: 'Untitled draft' })
    const calls = writes(fetcher).filter(([path]) => path === '/api/v2/polls/')
    expect(calls).toHaveLength(1)
    expect(JSON.parse(String(calls[0]?.[1]?.body))).toEqual({
      question: '', description: '', category: null, visibility: 'public', voting_mode: 'single',
      min_selections: 1, max_selections: null, results_visibility: 'immediate', expires_at: null,
      options: [{ option_text: '' }, { option_text: '' }],
    })
    expect(state.poll?.status).toBe('draft')
    expect(route()).toBe(manage)
  })
  it('requires valid fields before opening publication review', async () => {
    const { fetcher } = fixture()
    await authenticatedApp('/polls/new')
    await userEvent.click(screen.getByRole('button', { name: 'Review & publish' }))
    expect(screen.getAllByText(/Enter a question before publishing/).length).toBeGreaterThan(0)
    expect(screen.getByLabelText('Question')).toHaveAttribute('aria-invalid', 'true')
    expect(writes(fetcher).filter(([path]) => path === '/api/v2/polls/')).toHaveLength(0)
    await fillQuestion()
    fireEvent.change(screen.getByLabelText('Option 2'), { target: { value: ' monday ' } })
    await userEvent.click(screen.getByRole('button', { name: 'Review & publish' }))
    expect(screen.getAllByText('Provide at least two distinct, nonempty options.').length).toBeGreaterThan(0)
    expect(screen.queryByRole('button', { name: 'Create and publish poll' })).not.toBeInTheDocument()
  })
  it('supports keyboard option addition/removal with predictable focus', async () => {
    fixture()
    await authenticatedApp('/polls/new')
    const user = userEvent.setup()
    screen.getByRole('button', { name: 'Add option' }).focus()
    await user.keyboard('{Enter}')
    const third = screen.getByLabelText('Option 3')
    await waitFor(() => expect(third).toHaveFocus())
    await user.type(third, 'Wednesday')
    await user.click(screen.getByRole('button', { name: 'Remove option 3' }))
    await waitFor(() => expect(screen.getByLabelText('Option 2')).toHaveFocus())
    expect(screen.queryByLabelText('Option 3')).not.toBeInTheDocument()
  })
  it('reviews then creates and publishes using separate confirmed requests', async () => {
    const { fetcher, state } = fixture()
    await authenticatedApp('/polls/new')
    await fillQuestion()
    await userEvent.selectOptions(screen.getByLabelText('Visibility'), 'private')
    await userEvent.selectOptions(screen.getByLabelText('Voting mode'), 'multiple')
    fireEvent.change(screen.getByLabelText('Minimum selections'), { target: { value: '1' } })
    fireEvent.change(screen.getByLabelText('Maximum selections'), { target: { value: '2' } })
    await userEvent.selectOptions(screen.getByLabelText('Results visibility'), 'after_voting')
    await userEvent.click(screen.getByRole('button', { name: 'Review & publish' }))
    const review = screen.getByRole('region', { name: 'Review and publish' })
    expect(screen.getByLabelText('Question')).toBeDisabled()
    expect(within(review).getByText('Monday')).toBeInTheDocument()
    expect(writes(fetcher).some(([path]) => path === '/api/v2/polls/')).toBe(false)
    await userEvent.click(within(review).getByRole('button', { name: 'Create and publish poll' }))
    await waitFor(() => expect(route()).toBe(manage))
    expect(state.poll).toMatchObject({ status: 'published', visibility: 'private', voting_mode: 'multiple', max_selections: 2, results_visibility: 'after_voting' })
    const paths = writes(fetcher).map(([path]) => path)
    expect(paths.indexOf('/api/v2/polls/')).toBeLessThan(paths.indexOf(detail + 'publish/'))
  })
  it('keeps a known draft after publication failure without reposting creation', async () => {
    const { state, fetcher } = fixture({}, path => path === detail + 'publish/' ? failure(400, { options: ['Backend publication validation failed.'] }) : undefined)
    await authenticatedApp('/polls/new')
    await fillQuestion()
    await userEvent.click(screen.getByRole('button', { name: 'Review & publish' }))
    await userEvent.click(screen.getByRole('button', { name: 'Create and publish poll' }))
    await waitFor(() => expect(route()).toBe(manage))
    expect(await screen.findByText(/Draft saved, but publication was not confirmed/)).toBeInTheDocument()
    expect(state.poll?.status).toBe('draft')
    expect(writes(fetcher).filter(([path]) => path === '/api/v2/polls/')).toHaveLength(1)
  })
  it('does not retry ambiguous creation errors and asks the creator to reconcile My polls', async () => {
    const { fetcher } = fixture({}, path => path === '/api/v2/polls/' ? failure(503) : undefined)
    await authenticatedApp('/polls/new')
    await userEvent.click(screen.getByRole('button', { name: 'Save draft' }))
    expect(await screen.findByRole('link', { name: 'Check My polls' })).toBeInTheDocument()
    expect(screen.getByRole('button', { name: 'Save draft' })).toBeDisabled()
    expect(writes(fetcher).filter(([path]) => path === '/api/v2/polls/')).toHaveLength(1)
  })
  it('blocks duplicate submissions while creation is pending', async () => {
    const pending = deferred<Response>()
    const { fetcher } = fixture({}, (path, init) => path === '/api/v2/polls/' && init.method === 'POST' ? pending.promise : undefined)
    const app = await authenticatedApp('/polls/new')
    const button = screen.getByRole('button', { name: 'Save draft' })
    fireEvent.click(button); fireEvent.click(button)
    await waitFor(() => expect(button).toBeDisabled())
    expect(writes(fetcher).filter(([path]) => path === '/api/v2/polls/')).toHaveLength(1)
    await act(async () => pending.resolve(json(draftPoll(), 201)))
    await waitFor(() => expect(route()).toBe(manage))
    app.unmount()
  })
  it('guards unsaved link navigation and browser refresh without persisting draft data', async () => {
    fixture()
    await authenticatedApp('/polls/new')
    await fillQuestion()
    const confirm = vi.spyOn(window, 'confirm').mockReturnValue(false)
    await userEvent.click(within(screen.getByRole('navigation', { name: 'Main' })).getByRole('link', { name: 'Explore polls' }))
    expect(confirm).toHaveBeenCalled()
    expect(route()).toBe('/polls/new')
    const event = new Event('beforeunload', { cancelable: true })
    window.dispatchEvent(event)
    expect(event.defaultPrevented).toBe(true)
    expect(localStorage.length).toBe(0)
    expect(sessionStorage.length).toBe(0)
  })
  it('passes accessible creation form semantics', async () => {
    fixture()
    await authenticatedApp('/polls/new')
    document.documentElement.lang = 'en'
    const result = await axe.run(document.body, { runOnly: { type: 'tag', values: ['wcag2a', 'wcag2aa', 'wcag21aa', 'wcag22aa'] }, rules: { 'color-contrast': { enabled: false } } })
    expect(result.violations.map(row => row.id)).toEqual([])
  })
})
describe('My polls and management', () => {
  it('shows only the signed-in creator list and synchronizes filters', async () => {
    const { fetcher } = fixture({ visibility: 'private' })
    await authenticatedApp('/my-polls?status=draft')
    expect(await screen.findByRole('link', { name: 'When should our community meet?' })).toHaveAttribute('href', manage)
    expect(screen.getByText('Private', { selector: 'span' })).toBeInTheDocument()
    await userEvent.selectOptions(screen.getByLabelText('Poll status'), 'archived')
    await screen.findByRole('heading', { name: 'No polls here yet.' })
    expect(route()).toContain('status=archived')
    expect(fetcher.mock.calls.some(([path]) => String(path).includes('/polls/mine/?') && String(path).includes('status=archived'))).toBe(true)
  })
  it('uses server pagination availability without following arbitrary response URLs', async () => {
    const { fetcher } = fixture({}, path => path.startsWith('/api/v2/polls/mine/') ? json({
      count: 21, next: path.includes('page=2') ? null : 'https://unsafe.invalid/next', previous: path.includes('page=2') ? 'previous' : null, results: [draftPoll()],
    }) : undefined)
    await authenticatedApp('/my-polls')
    await userEvent.click(await screen.findByRole('button', { name: 'Next page' }))
    await waitFor(() => expect(route()).toContain('page=2'))
    expect(fetcher.mock.calls.every(([path]) => !String(path).includes('unsafe.invalid'))).toBe(true)
  })
  it('rejects a response containing another creator rather than caching private data', async () => {
    fixture({}, path => path.startsWith('/api/v2/polls/mine/') ? json({ count: 1, next: null, previous: null, results: [draftPoll({ created_by: otherPollId, question: 'Other private question' })] }) : undefined)
    const { services } = await authenticatedApp('/my-polls')
    await screen.findByRole('button', { name: 'Retry My polls' })
    expect(screen.queryByText('Other private question')).not.toBeInTheDocument()
    expect(JSON.stringify(services.queryClient.getQueryCache().getAll().map(query => query.state.data))).not.toContain('Other private question')
  })
  it.each([403, 404])('hides owner controls for denied management (%s)', async status => {
    fixture({}, path => path === detail ? failure(status) : undefined)
    await authenticatedApp(manage)
    await screen.findByRole('heading', { name: 'Poll management unavailable.' })
    expect(screen.queryByRole('button', { name: 'Publish poll' })).not.toBeInTheDocument()
  })
  it('does not show management controls to an authenticated non-creator even with readable detail', async () => {
    fixture({ created_by: otherPollId })
    await authenticatedApp(manage)
    await screen.findByRole('heading', { name: 'Poll management unavailable.' })
    expect(screen.queryByLabelText('Question')).not.toBeInTheDocument()
  })
  it.each([null, true] as const)('keeps historical/voted configuration locked (%s)', async configuration_locked => {
    const { fetcher } = fixture({ configuration_locked, configuration_editable: false })
    await authenticatedApp(manage)
    const question = await screen.findByLabelText('Question')
    expect(question).toBeDisabled()
    expect(screen.getByLabelText('Visibility')).toBeDisabled()
    expect(screen.getByLabelText('Description (optional)')).toBeEnabled()
    expect(screen.queryByRole('button', { name: 'Add option' })).not.toBeInTheDocument()
    fireEvent.change(screen.getByLabelText('Description (optional)'), { target: { value: 'Updated description' } })
    await userEvent.click(screen.getByRole('button', { name: 'Save settings' }))
    await screen.findByText('Poll settings saved.')
    const patch = writes(fetcher).find(([path, init]) => path === detail && init?.method === 'PATCH')
    expect(JSON.parse(String(patch?.[1]?.body))).toEqual({ description: 'Updated description' })
  })
  it('rejects stale settings without losing edits after a refetch', async () => {
    const { state, fetcher } = fixture()
    const { services } = await authenticatedApp(manage)
    await screen.findByLabelText('Question')
    fireEvent.change(screen.getByLabelText('Question'), { target: { value: 'Unsaved question' } })
    state.poll!.version = 2
    await act(async () => services.queryClient.refetchQueries({ queryKey: ['creator-poll'] }))
    expect(screen.getByLabelText('Question')).toHaveValue('Unsaved question')
    await waitFor(() => expect(screen.getByRole('button', { name: 'Save settings' })).toBeDisabled())
    expect(writes(fetcher).some(([path, init]) => path === detail && init?.method === 'PATCH')).toBe(false)
    await userEvent.click(screen.getByRole('button', { name: 'Reload editor / discard changes' }))
    expect(screen.getByLabelText('Question')).toHaveValue(state.poll!.question)
  })
  it('edits/adds/removes options with separate confirmed requests', async () => {
    const { state, fetcher } = fixture()
    await authenticatedApp(manage)
    const edit = (await screen.findAllByRole('button', { name: 'Edit option' }))[0]!
    await userEvent.click(edit)
    fireEvent.change(screen.getByLabelText('Option text'), { target: { value: 'Evening' } })
    await userEvent.click(screen.getByRole('button', { name: 'Save option' }))
    await waitFor(() => expect(state.poll!.options[0]?.option_text).toBe('Evening'))
    await userEvent.click(screen.getByRole('button', { name: 'Add option' }))
    fireEvent.change(screen.getByLabelText('Option text'), { target: { value: 'Night' } })
    await userEvent.click(screen.getByRole('button', { name: 'Save option' }))
    await screen.findByText('Night')
    await userEvent.click(screen.getByRole('button', { name: 'Remove Night' }))
    expect(state.poll!.options.some(option => option.option_text === 'Night')).toBe(true)
    await userEvent.click(screen.getByRole('button', { name: 'Remove option' }))
    await waitFor(() => expect(state.poll!.options.some(option => option.option_text === 'Night')).toBe(false))
    expect(writes(fetcher).some(([path, init]) => String(path).includes('/options/') && init?.method === 'DELETE')).toBe(true)
  })
  it('makes archived polls read-only and never offers deletion or restoration', async () => {
    fixture({ status: 'archived' })
    await authenticatedApp(manage)
    expect(await screen.findByLabelText('Description (optional)')).toBeDisabled()
    expect(screen.queryByRole('button', { name: 'Save settings' })).not.toBeInTheDocument()
    expect(screen.queryByRole('button', { name: 'Reopen poll' })).not.toBeInTheDocument()
    expect(screen.queryByRole('button', { name: 'Delete draft' })).not.toBeInTheDocument()
  })
  it.each([
    ['draft', 'Publish poll', 'Confirm publish', 'published'],
    ['published', 'Close poll', 'Confirm close', 'closed'],
    ['closed', 'Archive poll', 'Confirm archive', 'archived'],
  ] as const)('confirms %s lifecycle actions before server mutation', async (status, button, confirm, expected) => {
    const { state, fetcher } = fixture({ status })
    await authenticatedApp(manage)
    await userEvent.click(await screen.findByRole('button', { name: button }))
    expect(state.poll?.status).toBe(status)
    expect(writes(fetcher).some(([path]) => String(path).endsWith('/' + expected + '/'))).toBe(false)
    await userEvent.click(screen.getByRole('button', { name: confirm }))
    await waitFor(() => expect(state.poll?.status).toBe(expected))
  })
  it('requires an explicit future date or no-expiration choice when reopening', async () => {
    const { state, fetcher } = fixture({ status: 'closed', expires_at: '2001-01-01T00:00:00Z' })
    await authenticatedApp(manage)
    await userEvent.click(await screen.findByRole('button', { name: 'Reopen poll' }))
    await userEvent.click(screen.getByRole('button', { name: 'Confirm reopen' }))
    expect(screen.getByText('Choose a future closing date or explicitly choose no expiration.')).toBeInTheDocument()
    expect(state.poll?.status).toBe('closed')
    await userEvent.click(screen.getByLabelText('Reopen with no expiration'))
    await userEvent.click(screen.getByRole('button', { name: 'Confirm reopen' }))
    await waitFor(() => expect(state.poll?.status).toBe('published'))
    const call = writes(fetcher).find(([path]) => path === detail + 'reopen/')
    expect(JSON.parse(String(call?.[1]?.body))).toEqual({ expires_at: null })
  })
  it('requires deletion confirmation and removes only a draft', async () => {
    const { state, fetcher } = fixture()
    await authenticatedApp(manage)
    await userEvent.click(await screen.findByRole('button', { name: 'Delete draft' }))
    expect(writes(fetcher).some(([, init]) => init?.method === 'DELETE')).toBe(false)
    await userEvent.click(screen.getByRole('button', { name: 'Permanently delete draft' }))
    await waitFor(() => expect(route()).toBe('/my-polls'))
    expect(state.poll).toBeNull()
  })
  it.each([400, 409, 503])('handles failed lifecycle operations without claiming success (%s)', async status => {
    fixture({}, path => path === detail + 'publish/' ? failure(status, { status: ['Cannot publish now.'] }) : undefined)
    await authenticatedApp(manage)
    await userEvent.click(await screen.findByRole('button', { name: 'Publish poll' }))
    await userEvent.click(screen.getByRole('button', { name: 'Confirm publish' }))
    await screen.findByRole('alert')
    expect(screen.queryByText('Poll published.')).not.toBeInTheDocument()
  })
  it('invalidates public discovery after confirmed settings changes', async () => {
    fixture()
    const { services } = await authenticatedApp(manage)
    await screen.findByLabelText('Question')
    services.queryClient.setQueryData(['public-polls', {}], { count: 0, next: null, previous: null, results: [] })
    fireEvent.change(screen.getByLabelText('Description (optional)'), { target: { value: 'Changed' } })
    await userEvent.click(screen.getByRole('button', { name: 'Save settings' }))
    await screen.findByText('Poll settings saved.')
    expect(services.queryClient.getQueryState(['public-polls', {}])?.isInvalidated).toBe(true)
  })
})

it('requires reconciliation after an interrupted option creation instead of posting it twice', async () => {
  const { state, fetcher } = fixture({}, (path, init) => {
    if (path === detail + 'options/' && init.method === 'POST') {
      state.poll!.options.push({ id: otherPollId, option_text: 'Night' })
      state.poll!.version!++
      return failure(503)
    }
    return undefined
  })
  await authenticatedApp(manage)
  await userEvent.click(await screen.findByRole('button', { name: 'Add option' }))
  fireEvent.change(screen.getByLabelText('Option text'), { target: { value: 'Night' } })
  await userEvent.click(screen.getByRole('button', { name: 'Save option' }))
  await screen.findByRole('button', { name: 'Reload options' })
  expect(screen.getByRole('button', { name: 'Save option' })).toBeDisabled()
  await userEvent.click(screen.getByRole('button', { name: 'Reload options' }))
  await screen.findByText('Options reloaded. Review the list before adding another option.')
  expect(screen.getByText('Night')).toBeInTheDocument()
  expect(writes(fetcher).filter(([path, init]) => path === detail + 'options/' && init?.method === 'POST')).toHaveLength(1)
})
